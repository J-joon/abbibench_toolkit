def render_contract_py(*, display_name: str) -> str:
    return textwrap.dedent(
        f"""
        from __future__ import annotations

        from dataclasses import dataclass
        from pathlib import Path

        import pandas as pd
        from abbibench_toolkit_core.data.repo import BENCHMARKING_SUFFIX, normalize_csv_dataset_id


        # ----------------------------
        # Contract constants
        # ----------------------------

        # Output column name used for correlation (default).
        SCORE_COLUMN = "log-likelihood"

        # Preferred identifier columns (keep any that exist in the GT CSV).
        ID_COLUMN_CANDIDATES: tuple[str, ...] = (
            "heavy_chain_seq",
            "light_chain_seq",
            "mut_heavy_chain_seq",
            "mut_light_chain_seq",
            "antigen_seq",
            "mut_antigen_seq",
        )

        # Ground-truth column required by the benchmark.
        GT_COLUMN = "binding_score"

        # Output file name suffix.
        OUTPUT_SUFFIX = "_scores.csv"


        def resolve_dataset_id(dataset_id: str) -> str:
            \"\"\"
            Map user-facing dataset id to the canonical on-disk dataset id.

            This MUST match toolkit-core behavior so that:
              - GT lookup succeeds
              - output filenames are canonical
            \"\"\"
            return normalize_csv_dataset_id(dataset_id)


        def select_id_columns(df: pd.DataFrame) -> list[str]:
            \"\"\"Select identifier columns to carry into outputs (intersection of candidates and df columns).\"\"\"
            return [c for c in ID_COLUMN_CANDIDATES if c in df.columns]


        def gt_csv_path(root_dir: Path, dataset_id: str) -> Path:
            ds = resolve_dataset_id(dataset_id)
            return root_dir / "data" / "binding_affinity" / f"{{ds}}{{BENCHMARKING_SUFFIX}}"


        def output_csv_path(root_dir: Path, dataset_id: str, model_id: str) -> Path:
            ds = resolve_dataset_id(dataset_id)
            return root_dir / "outputs" / f"{{ds}}_benchmarking_data_{{model_id}}_scores.csv"


        @dataclass(frozen=True)
        class ContractInfo:
            model_id: str = "{display_name}"
            score_column: str = SCORE_COLUMN
        """
    ).strip() + "\n"


def render_io_py() -> str:
    return textwrap.dedent(
        """
        from __future__ import annotations

        from pathlib import Path
        import pandas as pd


        def write_scores_csv(df: pd.DataFrame, path: Path, *, overwrite: bool = False) -> None:
            path.parent.mkdir(parents=True, exist_ok=True)
            if path.exists() and not overwrite:
                raise FileExistsError(f"Refusing to overwrite existing output: {path}")
            df.to_csv(path, index=False)
        """
    ).strip() + "\n"


