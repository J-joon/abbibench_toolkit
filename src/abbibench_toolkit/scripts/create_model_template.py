def render_pyproject(
    *,
    project_name: str,
    dist_name: str,
    version: str,
    description: str,
    authors: str,
    email: str,
    toolkit_rel_dep: str,
    entrypoint: str,
) -> str:
    # Keep deps minimal; users add torch/jax/etc themselves.
    #
    # IMPORTANT:
    #   We include a local file: dependency on the toolkit repo so the model package can import it.
    #   Hatchling blocks direct references by default; enable them explicitly.
    return textwrap.dedent(
        f"""
        [project]
        name = "{dist_name}"
        version = "{version}"
        description = "{description}"
        readme = "README.md"
        requires-python = ">=3.10"
        authors = [{{ name = "{authors}", email = "{email}" }}]
        dependencies = [
          "pandas>=2.0",
          "numpy>=1.24",
          "scipy>=1.10",
          "tyro>=0.8",
          # Local dependency on the toolkit repository (this repo).
          # If you move this model package elsewhere, change this to an sdist/wheel/published package.
          "abbibench_toolkit",
        ]

        [project.scripts]
        {entrypoint} = "{project_name}.cli:main"

        [build-system]
        requires = ["hatchling>=1.21"]
        build-backend = "hatchling.build"

        # Hatchling disallows direct references (e.g., "pkg @ file:../..") by default.
        # We use a local dependency on the toolkit repo in templates, so allow it.
        [tool.hatch.metadata]
        allow-direct-references = true

        [tool.hatch.build.targets.wheel]
        packages = ["src/{project_name}"]
        """
    ).strip() + "\n"


def render_readme(*, display_name: str, entrypoint: str) -> str:
    return textwrap.dedent(
        f"""
        # {display_name} (AbBiBench Toolkit Model Package)

        This is a **user model package template** generated by the AbBiBench Toolkit.
        It is designed to follow the toolkit's **scoring output contract** so that:

        - you can run your model inference with `uv`,
        - it writes CSV outputs to `./outputs`,
        - `make_table.py` can pick them up automatically and compute Spearman correlations.

        ## Quickstart

        From this directory:

        ```bash
        # Run inference + write outputs under the toolkit repo's ./outputs
        uv run {entrypoint} --root-dir ../.. --datasets 1mlc 2fjg
        ```

        The command will write files like:

        ```
        <toolkit_root>/outputs/<DATASET>_benchmarking_data_{display_name}_scores.csv
        ```

        ## What you need to implement

        Edit `src/.../model.py`:

        - implement `Model.score_dataframe(df, dataset_id)` to return a 1D array/Series of floats
        - the output is written to the `log-likelihood` column (contract default)

        ## Notes

        - The template reads ground-truth CSVs from:
          `<root_dir>/data/binding_affinity/<DATASET>_benchmarking_data.csv`
        - It writes prediction CSVs to:
          `<root_dir>/outputs/..._scores.csv`
        - It preserves identifier columns present in the GT CSV (e.g., `heavy_chain_seq`,
          `light_chain_seq`, `mut_heavy_chain_seq`, ...), so evaluation can merge safely.
        """
    ).strip() + "\n"


