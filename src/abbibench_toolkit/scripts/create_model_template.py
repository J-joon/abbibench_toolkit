def entrypoint() -> None:
    ap = argparse.ArgumentParser(description="Generate a uv-based AbBiBench model package template.")
    ap.add_argument("--name", required=True, help="Model display name (used in filenames, e.g., ProteinMPNN, MyModel)")
    ap.add_argument("--model-type", default="Other", help='Model type label (e.g., "Masked LM", "Inverse Folding")')
    ap.add_argument("--target-dir", default="models", help="Where to create the model package (default: ./models)")
    ap.add_argument("--repo-root", default=".", help="Toolkit repo root (default: current directory)")
    ap.add_argument("--author", default="Jaejoon Kim", help="Author name for pyproject metadata")
    ap.add_argument("--email", default="jjkim030309@gmail.com", help="Author email for pyproject metadata")
    ap.add_argument("--version", default="0.1.0", help="Initial package version")
    ap.add_argument("--overwrite", action="store_true", help="Overwrite files if they already exist")
    args = ap.parse_args()

    repo_root = Path(args.repo_root).resolve()
    if not (repo_root / "data").exists():
        raise FileNotFoundError(f"repo_root does not look like the benchmark root (missing ./data): {repo_root}")

    display_name = args.name.strip()
    slug = slugify(display_name)
    pkg = pkg_name_from_slug(slug)

    target_dir = Path(args.target_dir).resolve()
    pkg_dir = target_dir / slug.lower().replace("-", "_")

    dist_name = f"abbibench-model-{slug.lower().replace('_','-')}"
    entrypoint_name = f"abbibench-{slug.lower().replace('_','-')}"

    description = f"AbBiBench user model package: {display_name} ({args.model_type})"

    # Files
    pyproject = render_pyproject(
        project_name=pkg,
        dist_name=dist_name,
        version=args.version,
        description=description,
        authors=args.author,
        email=args.email,
        entrypoint=entrypoint_name,
    )
    readme = render_readme(display_name=display_name, entrypoint=entrypoint_name)
    gitignore = render_gitignore()

    init_py = render_init()
    contract_py = render_contract_py(display_name=display_name)
    io_py = render_io_py()
    model_py = render_model_py()
    cli_py = render_cli_py(display_name=display_name)

    # Write
    write_file(pkg_dir / "pyproject.toml", pyproject, overwrite=args.overwrite)
    write_file(pkg_dir / "README.md", readme, overwrite=args.overwrite)
    write_file(pkg_dir / ".gitignore", gitignore, overwrite=args.overwrite)

    src_dir = pkg_dir / "src" / pkg
    write_file(src_dir / "__init__.py", init_py, overwrite=args.overwrite)
    write_file(src_dir / "contract.py", contract_py, overwrite=args.overwrite)
    write_file(src_dir / "io.py", io_py, overwrite=args.overwrite)
    write_file(src_dir / "model.py", model_py, overwrite=args.overwrite)
    write_file(src_dir / "cli.py", cli_py, overwrite=args.overwrite)

    print("\nCreated model package template:")
    print(f"  {pkg_dir}")
    print("\nNext steps:")
    print(f"  cd {pkg_dir}")
    print(f"  uv run {entrypoint_name} --root-dir ../.. --datasets 1mlc 2fjg")
    print("\nThen implement your real model in:")
    print(f"  {src_dir / 'model.py'}")


if __name__ == "__main__":
    entrypoint()

