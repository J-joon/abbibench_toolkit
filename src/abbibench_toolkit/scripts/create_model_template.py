#!/usr/bin/env python3
"""
create_model_template.py

Create a uv-based Python package template that conforms to the AbBiBench-style
scoring output contract used by this toolkit.

Usage (run at repo root):
  python tools/create_model_template.py --name MyModel --model-type "Masked LM"

It will create:
  ./models/mymodel/
    pyproject.toml
    README.md
    .gitignore
    src/abbibench_model_mymodel/
      __init__.py
      cli.py
      model.py
      contract.py
      io.py

Then you can:
  cd models/mymodel
  uv run abbibench-mymodel --root-dir ../.. --datasets 1mlc 2fjg
"""

from __future__ import annotations

import argparse
import os
import re
import textwrap
from pathlib import Path


# ----------------------------
# Helpers
# ----------------------------

def slugify(name: str) -> str:
    s = name.strip()
    if not s:
        raise ValueError("Model name must be non-empty")
    # Keep alnum, underscore, hyphen; normalize separators to underscore for package name
    s = re.sub(r"[^\w\-]+", "_", s)
    s = s.strip("_")
    return s


def pkg_name_from_slug(slug: str) -> str:
    # Python import package name
    s = slug.lower().replace("-", "_")
    if not re.match(r"^[a-z_][a-z0-9_]*$", s):
        s = re.sub(r"^[^a-z_]+", "", s)
        s = re.sub(r"[^a-z0-9_]+", "_", s)
    if not s:
        raise ValueError(f"Cannot derive a valid python package name from: {slug!r}")
    return f"abbibench_model_{s}"


def relpath_posix(from_dir: Path, to_dir: Path) -> str:
    rel = os.path.relpath(to_dir, from_dir)
    return rel.replace(os.sep, "/")


def write_file(path: Path, content: str, *, overwrite: bool) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and not overwrite:
        raise FileExistsError(f"Refusing to overwrite existing file: {path}")
    path.write_text(content, encoding="utf-8")


