def render_cli_py(*, project_pkg: str, display_name: str, entrypoint: str) -> str:
    return textwrap.dedent(
        f"""
        from __future__ import annotations

        from dataclasses import dataclass
        from pathlib import Path
        from typing import Sequence

        import pandas as pd
        import tyro

        from .contract import ContractInfo, GT_COLUMN, select_id_columns, gt_csv_path, output_csv_path
        from .io import write_scores_csv
        from .model import Model


        @dataclass(frozen=True)
        class Args:
            \"\"\"Run model inference and emit contract-compliant score CSVs.\"\"\"

            # Toolkit repo root (contains ./data and ./outputs)
            root_dir: Path = Path("../..")

            # Dataset ids to score (user-facing ids; aliases resolved automatically)
            datasets: Sequence[str] = (
                "1mhp",
                "1mlc",
                "1n8z",
                "2fjg",
            )

            # Override model id used in output filename
            model_id: str = "{display_name}"

            # Score column name in output CSV (default: log-likelihood)
            score_column: str = "log-likelihood"

            # Overwrite existing outputs
            overwrite: bool = False

            # Emit extra debug prints
            verbose: bool = True


        def _load_gt(root_dir: Path, dataset_id: str) -> pd.DataFrame:
            p = gt_csv_path(root_dir, dataset_id)
            if not p.exists():
                raise FileNotFoundError(f"Missing GT CSV: {{p}}")
            df = pd.read_csv(p)
            if GT_COLUMN not in df.columns:
                raise KeyError(f"Missing required column '{{GT_COLUMN}}' in {{p}}. cols={{list(df.columns)}}")
            return df


        def run_one(root_dir: Path, dataset_id: str, model: Model, info: ContractInfo, *, score_column: str, overwrite: bool, verbose: bool) -> Path:
            gt = _load_gt(root_dir, dataset_id)
            id_cols = select_id_columns(gt)
            if not id_cols:
                # Still proceed with row-order evaluation, but keep this explicit.
                # make_table.py can fallback to row-order if no keys exist, but key-columns are recommended.
                if verbose:
                    print(f"[WARN] No ID columns found in GT for {{dataset_id}}. Proceeding with row-order outputs only.")

            scores = model.score_dataframe(gt, dataset_id)
            if len(scores) != len(gt):
                raise ValueError(f"Score length mismatch: got {{len(scores)}} scores but GT has {{len(gt)}} rows for {{dataset_id}}")

            out = pd.DataFrame()
            for c in id_cols:
                out[c] = gt[c]
            # Keep binding_score in the output for compatibility with some external scripts.
            out[GT_COLUMN] = gt[GT_COLUMN]
            out[score_column] = scores

            out_path = output_csv_path(root_dir, dataset_id, info.model_id)
            write_scores_csv(out, out_path, overwrite=overwrite)

            if verbose:
                print(f"[OK] wrote {{out_path}} (rows={{len(out)}} cols={{list(out.columns)}})")
            return out_path


        def main() -> None:
            a = tyro.cli(Args)
            root = a.root_dir.resolve()
            (root / "outputs").mkdir(parents=True, exist_ok=True)

            model = Model()
            info = ContractInfo(model_id=a.model_id)

            for ds in a.datasets:
                run_one(
                    root_dir=root,
                    dataset_id=ds,
                    model=model,
                    info=info,
                    score_column=a.score_column,
                    overwrite=a.overwrite,
                    verbose=a.verbose,
                )


        if __name__ == "__main__":
            main()
        """
    ).strip() + "\n"


# ----------------------------
# Main
# ----------------------------

def main() -> None:
    ap = argparse.ArgumentParser(description="Generate a uv-based AbBiBench model package template.")
    ap.add_argument("--name", required=True, help="Model display name (used in filenames, e.g., ProteinMPNN, MyModel)")
    ap.add_argument("--model-type", default="Other", help='Model type label (e.g., "Masked LM", "Inverse Folding")')
    ap.add_argument("--target-dir", default="models", help="Where to create the model package (default: ./models)")
    ap.add_argument("--repo-root", default=".", help="Toolkit repo root (default: current directory)")
    ap.add_argument("--author", default="Jaejoon Kim", help="Author name for pyproject metadata")
    ap.add_argument("--email", default="jjkim030309@gmail.com", help="Author email for pyproject metadata")
    ap.add_argument("--version", default="0.1.0", help="Initial package version")
    ap.add_argument("--overwrite", action="store_true", help="Overwrite files if they already exist")
    args = ap.parse_args()

    repo_root = Path(args.repo_root).resolve()
    if not (repo_root / "data").exists():
        raise FileNotFoundError(
            f"repo_root does not look like the toolkit root (missing ./data): {repo_root}"
        )

    display_name = args.name.strip()
    slug = slugify(display_name)
    pkg = pkg_name_from_slug(slug)

    target_dir = Path(args.target_dir).resolve()
    pkg_dir = target_dir / slug.lower().replace("-", "_")

    # Compute relative dependency to this toolkit repo root for pyproject.toml
    toolkit_rel = relpath_posix(pkg_dir, repo_root)
    if not toolkit_rel.startswith("."):
        toolkit_rel = "./" + toolkit_rel

    dist_name = f"abbibench-model-{slug.lower().replace('_','-')}"
    entrypoint = f"abbibench-{slug.lower().replace('_','-')}"

    description = f"AbBiBench user model package: {display_name} ({args.model_type})"

    # Files
    pyproject = render_pyproject(
        project_name=pkg,
        dist_name=dist_name,
        version=args.version,
        description=description,
        authors=args.author,
        email=args.email,
        toolkit_rel_dep=toolkit_rel,
        entrypoint=entrypoint,
    )
    readme = render_readme(display_name=display_name, entrypoint=entrypoint)
    gitignore = render_gitignore()

    init_py = render_init()
    contract_py = render_contract_py(display_name=display_name)
    io_py = render_io_py()
    model_py = render_model_py()
    cli_py = render_cli_py(project_pkg=pkg, display_name=display_name, entrypoint=entrypoint)

    # Write
    write_file(pkg_dir / "pyproject.toml", pyproject, overwrite=args.overwrite)
    write_file(pkg_dir / "README.md", readme, overwrite=args.overwrite)
    write_file(pkg_dir / ".gitignore", gitignore, overwrite=args.overwrite)

    src_dir = pkg_dir / "src" / pkg
    write_file(src_dir / "__init__.py", init_py, overwrite=args.overwrite)
    write_file(src_dir / "contract.py", contract_py, overwrite=args.overwrite)
    write_file(src_dir / "io.py", io_py, overwrite=args.overwrite)
    write_file(src_dir / "model.py", model_py, overwrite=args.overwrite)
    write_file(src_dir / "cli.py", cli_py, overwrite=args.overwrite)

    print("\nCreated model package template:")
    print(f"  {pkg_dir}")
    print("\nNext steps:")
    print(f"  cd {pkg_dir}")
    print(f"  uv run {entrypoint} --root-dir ../.. --datasets 1mlc 2fjg")
    print("\nThen implement your real model in:")
    print(f"  {src_dir / 'model.py'}")


if __name__ == "__main__":
    main()

