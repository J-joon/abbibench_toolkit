#!/usr/bin/env python3
"""
create_model_template.py

Create a uv-based Python package template that conforms to the AbBiBench-style
scoring output contract used by this toolkit.

Usage (run at toolkit repo root):
  python -m abbibench_toolkit.scripts.create_model_template --name MyModel --model-type "Masked LM"

It will create:
  ./models/mymodel/
    pyproject.toml
    README.md
    .gitignore
    src/abbibench_model_mymodel/
      __init__.py
      cli.py
      model.py
      contract.py
      io.py

Then you can:
  cd models/mymodel
  uv run abbibench-mymodel --root-dir ../.. --datasets 1mlc 2fjg
"""

from __future__ import annotations

import argparse
