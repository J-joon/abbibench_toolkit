def render_pyproject(
    *,
    project_name: str,
    dist_name: str,
    version: str,
    description: str,
    authors: str,
    email: str,
    entrypoint: str,
) -> str:
    """
    Generate pyproject.toml.

    NOTE:
      - We reference toolkit/core via git direct references as requested.
      - Hatchling blocks direct references unless allow-direct-references = true.
    """
    return textwrap.dedent(
        f"""
        [project]
        name = "{dist_name}"
        version = "{version}"
        description = "{description}"
        readme = "README.md"
        requires-python = ">=3.10"
        authors = [{{ name = "{authors}", email = "{email}" }}]
        dependencies = [
          "pandas>=2.0",
          "numpy>=1.24",
          "scipy>=1.10",
          "tyro>=0.8",
          # Toolkit deps via git (direct references).
          "abbibench_toolkit @ git+https://github.com/J-joon/abbibench_toolkit",
          "abbibench_toolkit_core @ git+https://github.com/J-joon/abbibench_toolkit_core",
        ]

        [project.scripts]
        {entrypoint} = "{project_name}.cli:main"

        [build-system]
        requires = ["hatchling>=1.21"]
        build-backend = "hatchling.build"

        [tool.hatch.metadata]
        allow-direct-references = true

        [tool.hatch.build.targets.wheel]
        packages = ["src/{project_name}"]
        """
    ).strip() + "\n"


