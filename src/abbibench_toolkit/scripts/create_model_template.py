def render_cli_py(*, display_name: str) -> str:
    return textwrap.dedent(
        f"""
        from __future__ import annotations

        from dataclasses import dataclass
        from pathlib import Path
        from typing import Sequence

        import pandas as pd
        import tyro

        from .contract import ContractInfo, GT_COLUMN, select_id_columns, gt_csv_path, output_csv_path
        from .io import write_scores_csv
        from .model import Model


        @dataclass(frozen=True)
        class Args:
            \"\"\"Run model inference and emit contract-compliant score CSVs.\"\"\"

            # Benchmark root (contains ./data and ./outputs)
            root_dir: Path = Path("../..")

            # Dataset ids to score (user-facing ids; normalized via toolkit-core)
            datasets: Sequence[str] = (
                "1mhp",
                "1mlc",
                "1n8z",
                "2fjg",
            )

            # Override model id used in output filename
            model_id: str = "{display_name}"

            # Score column name in output CSV (default: log-likelihood)
            score_column: str = "log-likelihood"

            # Overwrite existing outputs
            overwrite: bool = False

            # Emit extra debug prints
            verbose: bool = True


        def _load_gt(root_dir: Path, dataset_id: str) -> pd.DataFrame:
            p = gt_csv_path(root_dir, dataset_id)
            if not p.exists():
                raise FileNotFoundError(f"Missing GT CSV: {{p}}")
            df = pd.read_csv(p)
            if GT_COLUMN not in df.columns:
                raise KeyError(f"Missing required column '{{GT_COLUMN}}' in {{p}}. cols={{list(df.columns)}}")
            return df


        def run_one(
            *,
            root_dir: Path,
            dataset_id: str,
            model: Model,
            info: ContractInfo,
            score_column: str,
            overwrite: bool,
            verbose: bool,
        ) -> Path:
            gt = _load_gt(root_dir, dataset_id)
            id_cols = select_id_columns(gt)

            if not id_cols and verbose:
                print(f"[WARN] No ID columns found in GT for {{dataset_id}}. Proceeding with row-order outputs only.")

            scores = model.score_dataframe(gt, dataset_id)
            if len(scores) != len(gt):
                raise ValueError(
                    f"Score length mismatch: got {{len(scores)}} scores but GT has {{len(gt)}} rows for {{dataset_id}}"
                )

            out = pd.DataFrame()
            for c in id_cols:
                out[c] = gt[c]
            # Keep binding_score in output for compatibility with external scripts.
            out[GT_COLUMN] = gt[GT_COLUMN]
            out[score_column] = scores

            out_path = output_csv_path(root_dir, dataset_id, info.model_id)
            write_scores_csv(out, out_path, overwrite=overwrite)

            if verbose:
                print(f"[OK] wrote {{out_path}} (rows={{len(out)}} cols={{list(out.columns)}})")
            return out_path


        def main() -> None:
            a = tyro.cli(Args)
            root = a.root_dir.resolve()
            (root / "outputs").mkdir(parents=True, exist_ok=True)

            model = Model()
            info = ContractInfo(model_id=a.model_id)

            for ds in a.datasets:
                run_one(
                    root_dir=root,
                    dataset_id=ds,
                    model=model,
                    info=info,
                    score_column=a.score_column,
                    overwrite=a.overwrite,
                    verbose=a.verbose,
                )


        if __name__ == "__main__":
            main()
        """
    ).strip() + "\n"


